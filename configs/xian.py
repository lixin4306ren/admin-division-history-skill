# 西安政区变迁
#
# 口径同汉中：取治所设在本城的统县政区 —— 内史 → 京兆尹 → 京兆府 → 奉元路
# → 西安府 → 西安市。上级（司隶校尉部、关内道、永兴军路、陕西行省）进隶属带。
#
# 与汉中的对照：汉中的题眼是「改嫁」（元代从巴蜀改隶陕西），西安的题眼是
# 「降级」——904 年朱温挟昭宗迁都洛阳、拆毁长安，此后再未做过全国首都。
# 辖境上西安是真正的先扩后缩：西汉向东（华阴、潼关），唐向西北（咸阳、铜川），
# 元明达到极盛（相当今 5 个地级市），清雍正三年六州升直隶州后骤缩。

